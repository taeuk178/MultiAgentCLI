import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const rustSource = readFileSync(
  join(repoRoot, "src-tauri/src/providers/mod.rs"),
  "utf8",
);
const outPath = join(repoRoot, "src/lib/generated/providerTypes.ts");

function extractEnum(name) {
  const match = rustSource.match(new RegExp(`pub enum ${name} \\{([\\s\\S]*?)\\}`));
  if (!match) {
    throw new Error(`Could not find Rust enum ${name}`);
  }

  return match[1]
    .split("\n")
    .map((line) => line.replace(/\/\/.*$/, "").trim().replace(/,$/, ""))
    .filter(Boolean)
    .map((variant) => `"${variant.toLowerCase()}"`);
}

function extractStructFields(name) {
  const match = rustSource.match(new RegExp(`pub struct ${name} \\{([\\s\\S]*?)\\}`));
  if (!match) {
    throw new Error(`Could not find Rust struct ${name}`);
  }

  return match[1]
    .split("\n")
    .map((line) => line.trim().replace(/,$/, ""))
    .filter(Boolean)
    .map((line) => {
      const field = line.match(/^([a-z_]+):\s*(.+)$/);
      if (!field) {
        throw new Error(`Could not parse Rust field: ${line}`);
      }
      return [camelCase(field[1]), rustTypeToTs(field[2])];
    });
}

function camelCase(value) {
  return value.replace(/_([a-z])/g, (_, char) => char.toUpperCase());
}

function rustTypeToTs(type) {
  const trimmed = type.trim();
  if (trimmed.startsWith("Option<")) {
    return `${rustTypeToTs(trimmed.slice(7, -1))} | null`;
  }

  switch (trimmed) {
    case "String":
      return "string";
    case "u8":
    case "u64":
      return "number";
    case "ProviderId":
    case "HealthStatus":
      return trimmed;
    default:
      throw new Error(`Unsupported Rust type: ${type}`);
  }
}

const providerIds = extractEnum("ProviderId");
const healthStatuses = extractEnum("HealthStatus");
const runtimeFields = extractStructFields("ProviderRuntimeStatus");

const output = `// Generated by scripts/generate-provider-types.mjs. Do not edit directly.
// Source: src-tauri/src/providers/mod.rs

export type ProviderId = ${providerIds.join(" | ")};

export type HealthStatus = ${healthStatuses.join(" | ")};

export interface ProviderRuntimeStatus {
${runtimeFields.map(([name, type]) => `  ${name}: ${type};`).join("\n")}
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output);
